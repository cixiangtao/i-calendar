function copyFor({ activityId, activity, description }: FortuneItem): SignCopy {
  return (activityId && signCopy[activityId]) || [activity, description];
}

/** 保留 acer-almanac 的选签顺序，返回一条完整签文及最多两条短灵感。 */
export function createDailySign(day: Pick<CalendarDay, 'year' | 'month' | 'day'>) {
  const [lead, ...other] = generateFortuneV2(day).good;
  if (!lead) throw new Error('每日签缺少主签');

  const [title, body] = copyFor(lead);
  return { title, body, otherTitles: other.slice(0, 2).map((item) => copyFor(item)[0]) };
}
